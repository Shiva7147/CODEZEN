"use client";

import React, { useState } from "react";
import { ChevronDown } from "lucide-react";

export function FaqAccordion() {
  const [openIndex, setOpenIndex] = useState<number | null>(null); // Starts collapsed for clean minimal aesthetic

  const faqs = [
    {
      q: "How does Citation Verification guarantee zero AI hallucinations?",
      a: "Every finding generated by the hybrid model must return the exact Clause ID and a verbatim quote from that clause. Before the finding is displayed, Verity's Citation Verifier runs Bitap fuzzy search and token fidelity calculations against the stored source database. If the clause ID does not exist or the quote fails matching, the finding is automatically rejected or marked low confidence."
    },
    {
      q: "Why can't content creators dismiss sensitive claims alone?",
      a: "Based on evidence from our interview with Ananya (Compliance Reviewer), unsupported claims and financial/medical guarantees represent severe regulatory liabilities. Routine issues (typos, preferred terms) remain with creators and managers, but sensitive claims create a mandatory task for Authorised Reviewers and are locked from creator dismissal."
    },
    {
      q: "How does Guideline Clarity Insights separate employee training from ambiguous guidelines?",
      a: "Verity tracks creator disputes and overrides per clause. If a clause has a high dispute rate (>20%), the rule itself is ambiguous and requires corporate rewording. If a rule has a low dispute rate (<5%) but recurs frequently, the rule is clear but the team needs targeted training."
    },
    {
      q: "Why is a standard writing assistant not enough for brand governance?",
      a: "Writing assistants only polish syntax and tone in isolation. They have no grounding in an organization's approved guidelines, cannot determine who holds legal authority to approve a sensitive claim, maintain no tamper-evident audit history, and fail to identify which corporate guidelines are causing repeated mistakes."
    },
    {
      q: "Does Verity publish content directly to CMS or social platforms?",
      a: "No. As defined in our fixed Round 1 scope boundary, Verity is strictly a pre-publication governance workspace. It provides the approvals, verified diffs, and audit trail, but does not publish content to external distribution channels."
    }
  ];

  return (
    <section id="faq" className="mx-auto max-w-7xl px-4 sm:px-8 lg:px-12 py-16 sm:py-24 scroll-mt-24">
      <div className="flex flex-col md:flex-row md:items-end justify-between gap-4 mb-8">
        <div>
          <h2 className="text-2xl sm:text-3xl font-normal tracking-tight text-foreground">
            Before you start
          </h2>
        </div>
        <p className="text-xs sm:text-sm text-muted-foreground max-w-md md:text-right">
          Common questions on pre-publication governance, verification, and audit logs.
        </p>
      </div>

      <div className="rounded-2xl border border-border/70 bg-card p-6 sm:p-8 shadow-2xs divide-y divide-border/50">
        {faqs.map((faq, index) => {
          const isOpen = openIndex === index;
          return (
            <div key={index} className="py-4 first:pt-0 last:pb-0">
              <button
                type="button"
                onClick={() => setOpenIndex(isOpen ? null : index)}
                className="w-full flex items-center justify-between text-left text-sm font-medium text-foreground group"
              >
                <span className="group-hover:text-accent transition-colors">
                  {faq.q}
                </span>
                <ChevronDown
                  className={`size-4 text-muted-foreground transition-transform duration-200 shrink-0 ml-4 ${
                    isOpen ? "rotate-180" : ""
                  }`}
                />
              </button>

              {isOpen && (
                <p className="mt-3 text-xs sm:text-sm text-muted-foreground leading-relaxed font-normal animate-in fade-in duration-150">
                  {faq.a}
                </p>
              )}
            </div>
          );
        })}
      </div>
    </section>
  );
}
